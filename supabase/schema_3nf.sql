-- 6. CONVENIENT VIEWS (Joined Information)
-- ------------------------------------------------------------------------
create or replace view public.vw_farms as
select
    f.farm_id,
    f.farm_name,
    f.farmer_id,
    concat(fm.first_name, ' ', fm.last_name) as farmer_name,
    fm.contact_number as farmer_contact,
    f.location,
    f.area_hectares,
    f.soil_type_id,
    st.soil_type_name as soil_type,
    f.irrigation_type_id,
    it.irrigation_type_name as irrigation_type,
    f.created_at,
    f.updated_at
from public.farm f
join public.farmer fm on fm.farmer_id = f.farmer_id
join public.soil_types st on st.soil_type_id = f.soil_type_id
join public.irrigation_types it on it.irrigation_type_id = f.irrigation_type_id;

create or replace view public.vw_crops as
select
    c.crop_id,
    c.crop_name,
    c.variety,
    c.category_id,
    cc.category_name as crop_category,
    c.growing_period_days,
    c.season_id,
    rs.season_name as recommended_season,
    c.created_at,
    c.updated_at
from public.crop c
join public.crop_categories cc on cc.category_id = c.category_id
join public.recommended_seasons rs on rs.season_id = c.season_id;

create or replace view public.vw_plantings as
select
    p.planting_id,
    p.farm_id,
    f.farm_name,
    concat(fm.first_name, ' ', fm.last_name) as farmer_name,
    p.crop_id,
    c.crop_name,
    c.variety,
    p.planting_date,
    p.area_planted,
    p.seed_quantity,
    p.expected_harvest_date,
    p.status_id,
    ps.status_name as status,
    p.created_at,
    p.updated_at
from public.planting p
join public.farm f on f.farm_id = p.farm_id
join public.farmer fm on fm.farmer_id = f.farmer_id
join public.crop c on c.crop_id = p.crop_id
join public.planting_statuses ps on ps.status_id = p.status_id;

create or replace view public.vw_harvests as
select
    h.harvest_id,
    h.planting_id,
    f.farm_name,
    concat(fm.first_name, ' ', fm.last_name) as farmer_name,
    c.crop_name,
    p.planting_date,
    h.harvest_date,
    h.quantity_kg,
    h.selling_price_per_kg,
    (h.quantity_kg * h.selling_price_per_kg) as estimated_harvest_value,
    h.quality_grade_id,
    qg.grade_name as quality_grade,
    h.remark_id,
    hr.remark_description as remarks,
    h.remarks_note,
    h.created_at,
    h.updated_at
from public.harvest h
join public.planting p on p.planting_id = h.planting_id
join public.farm f on f.farm_id = p.farm_id
join public.farmer fm on fm.farmer_id = f.farmer_id
join public.crop c on c.crop_id = p.crop_id
join public.harvest_quality_grades qg on qg.quality_grade_id = h.quality_grade_id
join public.harvest_remarks hr on hr.remark_id = h.remark_id;

