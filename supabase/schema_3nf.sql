-- ------------------------------------------------------------------------
-- 1. SYSTEM USERS & ROLE-BASED ACCESS CONTROL
-- ------------------------------------------------------------------------
create table public.users (
    user_id integer generated by default as identity primary key,
    username varchar(50) not null unique,
    email varchar(100) not null unique,
    password_hash varchar(255) not null,
    full_name varchar(100) not null,
    role varchar(20) not null default 'staff' check (role in ('admin', 'staff')),
    status varchar(20) not null default 'active' check (status in ('active', 'inactive')),
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

-- ------------------------------------------------------------------------
-- 2. LOOKUP / REFERENCE TABLES (Controlled Dropdown Lists - 3NF)
-- ------------------------------------------------------------------------
create table public.crop_categories (
    category_id integer generated by default as identity primary key,
    category_name varchar(50) not null unique
);

create table public.recommended_seasons (
    season_id integer generated by default as identity primary key,
    season_name varchar(30) not null unique
);

create table public.soil_types (
    soil_type_id integer generated by default as identity primary key,
    soil_type_name varchar(50) not null unique
);

create table public.irrigation_types (
    irrigation_type_id integer generated by default as identity primary key,
    irrigation_type_name varchar(50) not null unique
);

create table public.planting_statuses (
    status_id integer generated by default as identity primary key,
    status_name varchar(30) not null unique
);

create table public.harvest_quality_grades (
    quality_grade_id integer generated by default as identity primary key,
    grade_name varchar(30) not null unique
);

create table public.harvest_remarks (
    remark_id integer generated by default as identity primary key,
    remark_description varchar(50) not null unique
);

-- ------------------------------------------------------------------------
-- 3. CORE ENTITY TABLES
-- ------------------------------------------------------------------------

-- Table: FARMER
create table public.farmer (
    farmer_id integer generated by default as identity primary key,
    first_name varchar(50) not null check (length(trim(first_name)) > 0),
    last_name varchar(50) not null check (length(trim(last_name)) > 0),
    contact_number varchar(20),
    address varchar(150) not null check (length(trim(address)) > 0),
    date_registered date not null default current_date,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

-- Table: FARM
create table public.farm (
    farm_id integer generated by default as identity primary key,
    farmer_id integer not null references public.farmer(farmer_id) on delete restrict on update cascade,
    farm_name varchar(100) not null check (length(trim(farm_name)) > 0),
    location varchar(150) not null check (length(trim(location)) > 0),
    area_hectares numeric(8,2) not null check (area_hectares > 0),
    soil_type_id integer not null references public.soil_types(soil_type_id) on delete restrict on update cascade,
    irrigation_type_id integer not null references public.irrigation_types(irrigation_type_id) on delete restrict on update cascade,
    deleted_at timestamptz default null,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

-- Table: CROP
create table public.crop (
    crop_id integer generated by default as identity primary key,
    crop_name varchar(80) not null check (length(trim(crop_name)) > 0),
    variety varchar(80),
    category_id integer not null references public.crop_categories(category_id) on delete restrict on update cascade,
    growing_period_days integer not null check (growing_period_days > 0),
    season_id integer not null references public.recommended_seasons(season_id) on delete restrict on update cascade,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    unique(crop_name, variety)
);

-- Table: PLANTING
create table public.planting (
    planting_id integer generated by default as identity primary key,
    farm_id integer not null references public.farm(farm_id) on delete restrict on update cascade,
    crop_id integer not null references public.crop(crop_id) on delete restrict on update cascade,
    planting_date date not null,
    area_planted numeric(8,2) not null check (area_planted > 0),
    seed_quantity numeric(8,2) check (seed_quantity is null or seed_quantity >= 0),
    expected_harvest_date date check (expected_harvest_date is null or expected_harvest_date >= planting_date),
    status_id integer not null references public.planting_statuses(status_id) on delete restrict on update cascade,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

-- Table: HARVEST
create table public.harvest (
    harvest_id integer generated by default as identity primary key,
    planting_id integer not null references public.planting(planting_id) on delete restrict on update cascade,
    harvest_date date not null,
    quantity_kg numeric(10,2) not null check (quantity_kg > 0),
    selling_price_per_kg numeric(10,2) not null check (selling_price_per_kg >= 0),
    quality_grade_id integer not null references public.harvest_quality_grades(quality_grade_id) on delete restrict on update cascade,
    remark_id integer not null references public.harvest_remarks(remark_id) on delete restrict on update cascade,
    remarks_note varchar(200),
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

