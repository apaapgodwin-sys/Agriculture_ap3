alter table public.crop_categories enable row level security;
alter table public.recommended_seasons enable row level security;
alter table public.soil_types enable row level security;
alter table public.irrigation_types enable row level security;
alter table public.planting_statuses enable row level security;
alter table public.harvest_quality_grades enable row level security;
alter table public.harvest_remarks enable row level security;
alter table public.farmer enable row level security;
alter table public.farm enable row level security;
alter table public.crop enable row level security;
alter table public.planting enable row level security;
alter table public.harvest enable row level security;

do $$
declare
    tbl text;
begin
    foreach tbl in array array[
        'users', 'crop_categories', 'recommended_seasons', 'soil_types',
        'irrigation_types', 'planting_statuses', 'harvest_quality_grades',
        'harvest_remarks', 'farmer', 'farm', 'crop', 'planting', 'harvest'
    ] loop
        execute format('drop policy if exists "allow_anon_all_%1$s" on public.%1$s', tbl);
        execute format('create policy "allow_anon_all_%1$s" on public.%1$s for all to anon using (true) with check (true)', tbl);
        execute format('drop policy if exists "allow_auth_all_%1$s" on public.%1$s', tbl);
        execute format('create policy "allow_auth_all_%1$s" on public.%1$s for all to authenticated using (true) with check (true)', tbl);
    end loop;
end $$;

-- Grant permissions to public roles in Supabase
grant usage on schema public to anon, authenticated, service_role;
grant all on all tables in schema public to anon, authenticated, service_role;
grant all on all sequences in schema public to anon, authenticated, service_role;
grant all on all routines in schema public to anon, authenticated, service_role;

-- Notify PostgREST to reload schema cache
notify pgrst, 'reload schema';
