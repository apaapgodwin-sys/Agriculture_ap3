-- 5. AUTOMATIC AUDIT TIMESTAMP TRIGGER
-- ------------------------------------------------------------------------
create or replace function public.update_timestamp()
returns trigger language plpgsql as $$
begin
    new.updated_at = now();
    return new;
end;
$$;

create trigger trg_farmer_updated_at before update on public.farmer for each row execute procedure public.update_timestamp();
create trigger trg_farm_updated_at before update on public.farm for each row execute procedure public.update_timestamp();
create trigger trg_crop_updated_at before update on public.crop for each row execute procedure public.update_timestamp();
create trigger trg_planting_updated_at before update on public.planting for each row execute procedure public.update_timestamp();
create trigger trg_harvest_updated_at before update on public.harvest for each row execute procedure public.update_timestamp();
create trigger trg_users_updated_at before update on public.users for each row execute procedure public.update_timestamp();

